/**
 * Copies common-connect's source into each application.
 *
 * Connect builds an application from its own folder: `../common-connect`
 * is not reachable there, at install time or at build time, so a `file:`
 * dependency on it cannot resolve. The shared code is therefore vendored
 * — one source of truth in common-connect/src, a generated copy in each
 * application under src/shared.
 *
 * The copies are committed, so a checkout builds without running
 * anything. `--check` fails when they have drifted, which is what keeps
 * "one source of truth" true; predeploy runs it.
 */
import { readdirSync, readFileSync, mkdirSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'common-connect', 'src');
const apps = ['product-extension', 'rules-api', 'category-event', 'sweep-job'];

const HEADER = `// Generated by tools/sync-shared.mjs from common-connect/src. Do not edit.
// Edit the original and run \`npm run sync:shared\` at the repository root.
`;

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return entry.name.endsWith('.ts') ? [full] : [];
  });

const files = walk(source).map((full) => ({
  relativePath: relative(source, full),
  contents: HEADER + readFileSync(full, 'utf8'),
}));

const check = process.argv.includes('--check');
let drifted = 0;

for (const app of apps) {
  const target = join(root, app, 'src', 'shared');

  if (!check) {
    rmSync(target, { recursive: true, force: true });
  }

  for (const file of files) {
    const destination = join(target, file.relativePath);
    if (check) {
      const current = existsSync(destination) ? readFileSync(destination, 'utf8') : '';
      if (current !== file.contents) {
        process.stdout.write(`drifted: ${relative(root, destination)}\n`);
        drifted++;
      }
      continue;
    }
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, file.contents);
  }

  if (check && existsSync(target)) {
    const extra = walk(target)
      .map((full) => relative(target, full))
      .filter((path) => !files.some((file) => file.relativePath === path));
    for (const path of extra) {
      process.stdout.write(`stale: ${relative(root, join(target, path))}\n`);
      drifted++;
    }
  }
}

if (check && drifted) {
  process.stderr.write(
    `\n${drifted} shared file(s) out of step. Run \`npm run sync:shared\`.\n`
  );
  process.exit(1);
}

process.stdout.write(
  check
    ? `Shared code is in step across ${apps.length} applications.\n`
    : `Synced ${files.length} file(s) into ${apps.length} applications.\n`
);
